// Writes src/content/stockLogos.ts from the two SOURCES.json files the fetch scripts keep.
// Run after fetch-stock-logos.mjs or fetch-company-logos.mjs.
import fs from 'node:fs'
const tokens = JSON.parse(fs.readFileSync('public/tokens/SOURCES.json', 'utf8'))
const companies = JSON.parse(fs.readFileSync('public/tokens/logos/SOURCES.json', 'utf8'))
const byToken = Object.fromEntries(Object.entries(tokens).filter(([k]) => k.includes('/0x')).map(([k, v]) => [k, v.file]))
const byTicker = Object.fromEntries(Object.entries(companies).map(([k, v]) => [k, v.file]))
fs.writeFileSync(
  'src/content/stockLogos.ts',
  `/* Generated by scripts/gen-logo-index.mjs. Do not edit.
   byToken: the token's own logo where it carries the company mark (BSC bStocks, from the issuer's listing).
   byTicker: the company's own site icon, used where the token's logo is generic (Robinhood's feather).
   Sources: public/tokens/SOURCES.json and public/tokens/logos/SOURCES.json. */
export const logoByToken: Record<string, string> = ${JSON.stringify(byToken, null, 2)}

export const logoByTicker: Record<string, string> = ${JSON.stringify(byTicker, null, 2)}
`,
)
console.log(Object.keys(byToken).length, 'token logos,', Object.keys(byTicker).length, 'company logos')
