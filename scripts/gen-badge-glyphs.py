#!/usr/bin/env python
"""Outlines the badge type to SVG paths, once, at build time: server/badge-glyphs.mjs.

    python scripts/gen-badge-glyphs.py

Badges (server/badges.mjs) never ask the viewer for a font: every letter is a path out of the kit's own typefaces,
Barlow Condensed 700 (display) and JetBrains Mono 500 (utility), the two the brand kit names in tokens/tokens.json.
This script reads the font files with fontTools, walks each glyph with an SVG pen (quadratic outlines, y up,
whole font units) and writes the paths with their advance widths. It also embeds the two kit marks
(public/brand/kit/mark-64.png and mark-128.png, cut from the kit's mascot bust by scripts/brand-icons.py) as data
URIs, so the renderer needs no file reads and the Docker image (which copies server/*.mjs) needs no extra files.

Fonts: Barlow Condensed 700 from @fontsource/barlow-condensed (node_modules), JetBrains Mono 500 from
scripts/brand-kit/jetbrains-mono-latin-500-normal.woff2 (the kit's file, OFL).
"""
import base64, json, os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONTS = {
    'display': dict(family='Barlow Condensed', weight=700, file=os.path.join(ROOT, 'node_modules', '@fontsource', 'barlow-condensed', 'files', 'barlow-condensed-latin-700-normal.woff')),
    'mono': dict(family='JetBrains Mono', weight=500, file=os.path.join(ROOT, 'scripts', 'brand-kit', 'jetbrains-mono-latin-500-normal.woff2')),
}
CHARS = [chr(c) for c in range(32, 127)] + ['\u00b7', '\u2014', '\u2013', '\u2026']


def outline(path):
    f = TTFont(path)
    cmap = f.getBestCmap()
    gs = f.getGlyphSet()
    hmtx = f['hmtx']
    upm = f['head'].unitsPerEm
    glyphs = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            continue
        pen = SVGPathPen(gs, ntos=lambda v: str(int(round(v))))
        gs[name].draw(pen)
        glyphs[ch] = {'a': hmtx[name][0], 'd': pen.getCommands()}
    os2 = f['OS/2']
    return {'upm': upm, 'cap': getattr(os2, 'sCapHeight', 0), 'xh': getattr(os2, 'sxHeight', 0), 'glyphs': glyphs}


out = {'fonts': {}, 'marks': {}}
for key, spec in FONTS.items():
    if not os.path.exists(spec['file']):
        sys.exit('font not found: ' + spec['file'])
    o = outline(spec['file'])
    o['family'], o['weight'] = spec['family'], spec['weight']
    out['fonts'][key] = o
for px in (64, 128):
    with open(os.path.join(ROOT, 'public', 'brand', 'kit', f'mark-{px}.png'), 'rb') as fh:
        out['marks'][str(px)] = 'data:image/png;base64,' + base64.b64encode(fh.read()).decode()

head = ('// Generated by scripts/gen-badge-glyphs.py from the kit typefaces (Barlow Condensed 700, JetBrains Mono 500) and the kit marks.\n'
        '// Do not edit: run the script. Glyph paths are quadratic outlines in font units, y up; `a` is the advance width.\n')
with open(os.path.join(ROOT, 'server', 'badge-glyphs.mjs'), 'w', encoding='utf8', newline='\n') as fh:
    fh.write(head + 'export default ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '\n')
print('wrote server/badge-glyphs.mjs', {k: (v['upm'], v['cap'], len(v['glyphs'])) for k, v in out['fonts'].items()})
