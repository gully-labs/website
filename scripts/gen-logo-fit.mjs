// Writes src/content/logoFit.ts: how each stock logo sits in its round, white disc, measured from the
// file itself so none is cropped by the circle. Run after gen-logo-index.mjs (needs Playwright's Chromium).
//
//   full   the file is already a filled tile or disc (opaque corners, or an opaque ring just inside the
//          edge): it fills the circle, which trims only its own corners or rim.
//   scale  otherwise a mark on transparency: the share of the disc it may take so that its farthest
//          painted pixel stays inside the circle with a margin (at most 0.82, the old fixed size).
import fs from 'node:fs'
import path from 'node:path'
import { chromium } from 'playwright'

const src = fs.readFileSync('src/content/stockLogos.ts', 'utf8')
const files = [...new Set([...src.matchAll(/"(\/tokens\/[^"]+)"/g)].map((m) => m[1]))]
const TYPES = { '.png': 'image/png', '.svg': 'image/svg+xml', '.ico': 'image/x-icon', '.jpg': 'image/jpeg', '.webp': 'image/webp' }

const browser = await chromium.launch()
const page = await browser.newPage()
await page.route('http://logos.local/**', (r) => {
  const p = new URL(r.request().url()).pathname
  if (p === '/') return r.fulfill({ body: '<!doctype html><title>fit</title>', contentType: 'text/html' })
  return r.fulfill({ body: fs.readFileSync(path.join('public', decodeURIComponent(p))), contentType: TYPES[path.extname(p)] ?? 'application/octet-stream' })
})
await page.goto('http://logos.local/')
const fit = {}
for (const f of files) {
  fit[f] = await page.evaluate(async (url) => {
    const img = new Image()
    img.src = url
    await img.decode()
    const N = 128
    const c = document.createElement('canvas')
    c.width = c.height = N
    const g = c.getContext('2d')
    const w = img.naturalWidth || N
    const h = img.naturalHeight || N
    const k = Math.min(N / w, N / h)
    g.drawImage(img, (N - w * k) / 2, (N - h * k) / 2, w * k, h * k)
    const a = g.getImageData(0, 0, N, N).data
    const alpha = (x, y) => a[(Math.round(y) * N + Math.round(x)) * 4 + 3]
    const corners = [
      [3, 3],
      [N - 4, 3],
      [3, N - 4],
      [N - 4, N - 4],
    ].every(([x, y]) => alpha(x, y) > 200)
    let ring = 0
    for (let i = 0; i < 72; i++) {
      const t = (i / 72) * 2 * Math.PI
      if (alpha(N / 2 + Math.cos(t) * N * 0.46, N / 2 + Math.sin(t) * N * 0.46) > 200) ring++
    }
    if (corners || ring >= 70) return { full: true, scale: 1 }
    let dmax = 0
    for (let y = 0; y < N; y++)
      for (let x = 0; x < N; x++)
        if (a[(y * N + x) * 4 + 3] > 40) dmax = Math.max(dmax, Math.hypot(x + 0.5 - N / 2, y + 0.5 - N / 2) / (N / 2))
    return { full: false, scale: Math.round(Math.min(0.82, 0.8 / Math.max(dmax, 0.01)) * 100) / 100 }
  }, `http://logos.local${f}`)
}
await browser.close()
fs.writeFileSync(
  'src/content/logoFit.ts',
  `/* Generated by scripts/gen-logo-fit.mjs. Do not edit.
   How each stock logo sits in its disc: full (a filled tile or disc that fills the circle) or the share
   of the disc a transparent mark takes so the circle never crops it. */
export const logoFit: Record<string, { full: boolean; scale: number }> = ${JSON.stringify(fit, null, 2)}
`,
)
console.log(files.length, 'logos measured;', Object.values(fit).filter((v) => v.full).length, 'fill the disc')
