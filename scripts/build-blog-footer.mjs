// Builds the blog theme's footer from the shared footer data (server/data/footer.json on feat/footer-data, then main).
//   node scripts/build-blog-footer.mjs                       render ghost/theme/gully/partials/footer.hbs from the pinned copy
//   node scripts/build-blog-footer.mjs --pin <dir> <sha>     pin a new copy: <dir> holds footer.json and landing-icons.mjs
// The pinned copy is ghost/footer-data.json, its commit is in ghost/footer-data.pin. Missing Lucide icons are written as
// theme partials from landing-icons.mjs (the same Lucide set the website draws).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const THEME = path.join(ROOT, 'ghost/theme/gully')
const DATA = path.join(ROOT, 'ghost/footer-data.json')
const SITE = 'https://gullylabs.xyz'
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')
const abs = (h) => (h.startsWith('/') ? SITE + h : h)

export function renderFooter(data) {
  const entry = (l, style) => {
    const href = abs(l.href)
    const own = new URL(href).host === 'blog.gullylabs.xyz'
    return `{{> "nav-entry" style="${style}"${own ? '' : ' ext=true'} href="${href}" icon="${l.icon}" label="${esc(l.label)}"}}`
  }
  const col = (c, cls) => `            <nav class="gl-footer-col${cls}" data-col="${c.id}" aria-labelledby="gl-foot-${c.id}">
                <h2 class="gl-footer-head" id="gl-foot-${c.id}">${esc(c.title)}</h2>
                <ul class="gl-footer-list" role="list">
${c.links.map((l) => '                    ' + entry(l, 'footer')).join('\n')}
                </ul>
            </nav>`
  const cols = [...data.columns.map((c) => col(c, '')), col({ id: 'peddle', title: data.peddle.title, links: data.peddle.links }, '')].join('\n')
  const legal = data.legal.map((l) => `<a href="${abs(l.href)}" target="_blank" rel="noopener noreferrer">${esc(l.label)}</a>`).join('\n                ')
  return `{{!-- GENERATED by scripts/build-blog-footer.mjs from ghost/footer-data.json (pinned copy of server/data/footer.json, commit in ghost/footer-data.pin). Do not edit by hand. --}}
<footer class="gl-footer">
    <div class="gl-footer-main gl-page">
        <div class="gl-footer-brand">
            <a class="gl-footer-logo" href="${SITE}" target="_blank" rel="noopener noreferrer">
                {{> "brand/logo"}}<span class="gl-sr"> Gully Labs home (opens in a new tab)</span>
            </a>
            <p class="gl-footer-tagline">${esc(data.brand.tagline)}</p>
        </div>
        <div class="gl-footer-cols">
${cols}
        </div>
    </div>
    <div class="gl-footer-legal gl-page">
        <div class="gl-footer-legal-left">
            <span class="gl-footer-copy">${esc(data.brand.copy)}</span>
            <nav class="gl-footer-legal-links" aria-label="Legal">
                ${legal}
            </nav>
        </div>
        {{> "brand/badge"}}
    </div>
</footer>
`
}

export const footerIcons = (data) => [...new Set([...data.columns.flatMap((c) => c.links), ...data.peddle.links, ...data.legal].map((l) => l.icon))]

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const pin = process.argv.indexOf('--pin')
  if (pin > 0) {
    const [dir, sha] = [process.argv[pin + 1], process.argv[pin + 2]]
    fs.copyFileSync(path.join(dir, 'footer.json'), DATA)
    fs.writeFileSync(path.join(ROOT, 'ghost/footer-data.pin'), `${sha}\n`)
    const { ICONS } = await import(pathToFileURL(path.join(dir, 'landing-icons.mjs')).href)
    for (const i of footerIcons(JSON.parse(fs.readFileSync(DATA, 'utf8')))) {
      const f = path.join(THEME, `partials/icons/${i}.hbs`)
      if (fs.existsSync(f)) continue
      if (!ICONS[i]) throw new Error(`no icon ${i}`)
      const body = ICONS[i].replace(/ \/>/g, '/>').replace(/\s+/g, ' ')
      fs.writeFileSync(f, `{{!-- lucide "${i}" (ISC) --}}\n<svg class="gl-icon gl-icon-${i}" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>\n`)
    }
  }
  fs.writeFileSync(path.join(THEME, 'partials/footer.hbs'), renderFooter(JSON.parse(fs.readFileSync(DATA, 'utf8'))))
}
