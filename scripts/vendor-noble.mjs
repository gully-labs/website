// Regenerates server/vendor/noble.mjs: the @noble/curves (secp256k1) and @noble/hashes (keccak_256)
// bundled into one dependency-free ES module, so the production server (which installs no node_modules)
// can verify Sign-In with Ethereum signatures. Both libraries are MIT, by Paul Miller (paulmillr.com).
// Also the ERC-6492 validator bytecode from viem (MIT), for smart wallets that are not deployed yet.
//   node scripts/vendor-noble.mjs
import { build } from 'esbuild'
import fs from 'node:fs'

const curves = JSON.parse(fs.readFileSync('node_modules/@noble/curves/package.json', 'utf8')).version
const hashes = JSON.parse(fs.readFileSync('node_modules/@noble/hashes/package.json', 'utf8')).version
const viem = JSON.parse(fs.readFileSync('node_modules/viem/package.json', 'utf8')).version
const banner = `// GENERATED by scripts/vendor-noble.mjs. Do not edit.
// @noble/curves ${curves} (secp256k1) and @noble/hashes ${hashes} (keccak_256), MIT License,
// Copyright (c) 2022 Paul Miller (https://paulmillr.com). https://github.com/paulmillr/noble-curves
// erc6492SignatureValidatorByteCode from viem ${viem} (MIT, wevm), the ERC-6492 reference UniversalSigValidator.
`
await build({
  stdin: { contents: "export { secp256k1 } from '@noble/curves/secp256k1'\nexport { keccak_256 } from '@noble/hashes/sha3'\nexport { erc6492SignatureValidatorByteCode } from './node_modules/viem/_esm/constants/contracts.js'\n", resolveDir: process.cwd() },
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  outfile: 'server/vendor/noble.mjs',
  banner: { js: banner },
  legalComments: 'inline',
})
console.log('wrote server/vendor/noble.mjs')
