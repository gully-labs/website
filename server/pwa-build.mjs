// Build-time half of the PWA: the precache list from a Vite output bundle, the version stamp and the generated
// service worker (dist/sw.js). Used by vite.config.ts and scripts/test-pwa-unit.mjs. Rules: server/pwa.mjs.
import { createHash } from 'node:crypto'
import { routeFor, SW_RULES } from './pwa.mjs'

/* ------------------------------------------------------------------ build: precache list and worker --- */

const FIXED = ['/index.html', '/errors/offline.html', '/icon-192.png']
const isFont = (f) => /\.(woff2?|ttf|otf)$/.test(f)
// Fonts: only the latin subsets (fontsource ships one file per unicode range; the rest load on demand).
const wantAsset = (f) => (!isFont(f) || /-latin-\d+-/.test(f)) && /^assets\/.+-[\w-]{8}\./.test(f)

/**
 * The files the app shell needs on first paint, from a Rollup/Vite output bundle (fileName -> chunk or asset):
 * every entry chunk, its static imports (not the lazy chunks), the css they pull in and the latin fonts. Returns
 * URL paths: the fixed shell files first, then the hashed files sorted.
 */
export function buildPrecacheList(bundle) {
  const out = new Set()
  const seen = new Set()
  const visit = (name) => {
    const c = bundle[name]
    if (!c || c.type !== 'chunk' || seen.has(name)) return
    seen.add(name)
    if (wantAsset(c.fileName)) out.add('/' + c.fileName)
    for (const i of c.imports ?? []) visit(i)
    for (const f of [...(c.viteMetadata?.importedCss ?? []), ...(c.viteMetadata?.importedAssets ?? [])]) if (wantAsset(f)) out.add('/' + f)
  }
  for (const c of Object.values(bundle)) if (c.type === 'chunk' && c.isEntry) visit(c.fileName)
  return [...FIXED, ...[...out].sort()]
}

/** A short stamp that changes whenever any precached file does (hashed names carry content; the shell html is added). */
export function versionStamp(list, indexHtml = '') {
  return createHash('sha1').update(list.join('\n')).update('\n').update(String(indexHtml)).digest('hex').slice(0, 10)
}

const SW_BODY = `
const CACHE = 'gully-shell-' + VERSION
const SHELL = '/index.html'
const OFFLINE = '/errors/offline.html'

self.addEventListener('install', (event) => {
  // No skipWaiting here: a new worker waits until the page asks (the "New version available" card).
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })))))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('gully-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting()
})

self.addEventListener('fetch', (event) => {
  const req = event.request
  const route = routeFor(RULES, { url: req.url, method: req.method, mode: req.mode, origin: self.location.origin, hasAuth: req.headers.has('authorization') })
  if (route === 'asset') {
    event.respondWith(
      caches.open(CACHE).then((cache) =>
        cache.match(req).then(
          (hit) =>
            hit ||
            fetch(req).then((res) => {
              if (res.ok && res.status === 200) cache.put(req, res.clone())
              return res
            }),
        ),
      ),
    )
  } else if (route === 'navigate') {
    event.respondWith(
      fetch(req).catch(() =>
        caches.open(CACHE).then((cache) => cache.match(SHELL).then((shell) => shell || cache.match(OFFLINE))).then((res) => res || Response.error()),
      ),
    )
  }
})
`

/** The worker's source with the precache list, version and rules stamped in. */
export function generateSw({ precache, version }) {
  return `/* Gully Labs service worker (generated by the build from server/pwa.mjs; do not edit). Caching rules: see server/pwa.mjs. */
const VERSION = ${JSON.stringify(version)}
const PRECACHE = ${JSON.stringify(precache)}
const RULES = ${JSON.stringify(SW_RULES)}
${routeFor.toString()}
${SW_BODY}`
}

